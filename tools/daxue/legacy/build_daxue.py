PUNCT = '，。；：？！、'


def clean(s):
    for a, b in VARIANTS.items():
        s = s.replace(a, b)
    s = re.sub(r'[「」『』《》\s]', '', s)
    return s


def clauses_of(text):
    out = []
    for m in re.finditer(r'([^' + PUNCT + r']+)([' + PUNCT + r']*)', text):
        out.append({'t': m.group(1), 'p': m.group(2)})
    return out


