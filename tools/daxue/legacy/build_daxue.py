# 工具（大陸讀音）跟台灣讀音不同的字，整本統一改；OVR 仍可再覆寫
CHAR_FIX = {'子': 'ㄗˇ', '琢': 'ㄓㄨㄛˊ', '興': 'ㄒㄧㄥ', '盡': 'ㄐㄧㄣˋ',
            '逮': 'ㄉㄞˋ', '緝': 'ㄑㄧˋ', '為': 'ㄨㄟˊ'}
OVR.append(('曾子', 0, 'ㄗㄥ', '人名'))

stages = []
review = []
used_ovr = set()
for (cname, theme), body in zip(CHAPTERS, bodies):
    cl = clauses_of(clean(body))
    # 整章注音（用整章上下文判斷詞組）
    full = ''.join(c['t'] for c in cl)
    zh = [x[0] for x in pinyin(full, style=Style.BOPOMOFO, heteronym=False)]
    multi = [len(x) > 1 for x in pinyin(full, style=Style.BOPOMOFO, heteronym=True)]
    assert len(zh) == len(full), cname
    source = ['自動'] * len(full)
    for i, ch in enumerate(full):
        if ch in CHAR_FIX:
            zh[i] = CHAR_FIX[ch]
            source[i] = '改台灣讀音'
    for ctx, idx, z, why in OVR:
        for m in re.finditer(re.escape(ctx), full):
            zh[m.start() + idx] = z
            source[m.start() + idx] = '覆寫' + ('：' + why if why else '')
            used_ovr.add((ctx, idx))
    pos = 0
    for c in cl:
        n = len(c['t'])
        c['z'] = zh[pos:pos + n]
        for k in range(n):
            if multi[pos + k] or source[pos + k] != '自動':
                review.append((cname, c['t'], k, c['t'][k], c['z'][k], source[pos + k]))
        pos += n
    # 拆關
    cuts = [i for i, c in enumerate(cl) for s in SPLITS.get(cname, []) if c['t'].startswith(s)]
    bounds = [0] + cuts + [len(cl)]
    parts = len(bounds) - 1
    if cname in MERGE_INTO_PREV:
        prev = stages[-1]
        prev['chapter'] += '、' + cname
        prev['name'] = prev['name'] + '・' + cname
        prev['theme'] += '、' + theme
        prev['clauses'] += cl
        continue
    for j in range(parts):
        seg = cl[bounds[j]:bounds[j + 1]]
        label = cname + (['（上）', '（下）'] if parts == 2 else ['（一）', '（二）', '（三）'])[j] if parts > 1 else cname
        stages.append({'id': f'daxue-{len(stages) + 1:02d}', 'chapter': cname, 'name': label,
                       'theme': theme, 'clauses': seg})

neutral = sorted({(c['t'], c['t'][k]) for s in stages for c in s['clauses'] for k, z in enumerate(c['z']) if '˙' in z})
missing = [o for o in OVR if (o[0], o[1]) not in used_ovr]
data = {'id': 'daxue', 'title': '大學', 'source': '朱熹《大學章句》，維基文庫',
        'note': '異體字改為教育部標準字（脩→修、衆→眾、揜→掩），引號與書名號省略',
        'stages': stages}
json.dump(data, open('daxue.json', 'w', encoding='utf-8'), ensure_ascii=False, indent=1)

with open('build_log.txt', 'w', encoding='utf-8') as f:
    f.write(f'missing overrides: {missing}\n')
    for s in stages:
        f.write(f"{s['id']} {s['name']} {sum(len(c['t']) for c in s['clauses'])}字 {len(s['clauses'])}句\n")
json.dump(review, open('review.json', 'w', encoding='utf-8'), ensure_ascii=False)
